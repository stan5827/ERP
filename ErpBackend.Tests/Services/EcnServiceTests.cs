using System;
using System.Threading.Tasks;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Diagnostics;
using Xunit;
using ErpBackend.Data;
using ErpBackend.DTOs;
using ErpBackend.Models.MES;
using ErpBackend.Services;

namespace ErpBackend.Tests.Services;

public class EcnServiceTests
{
    private ErpGeneralDbContext CreateInMemoryDbContext()
    {
        var options = new DbContextOptionsBuilder<ErpGeneralDbContext>()
            .UseInMemoryDatabase(databaseName: Guid.NewGuid().ToString())
            .ConfigureWarnings(w => w.Ignore(InMemoryEventId.TransactionIgnoredWarning))
            .Options;
        return new ErpGeneralDbContext(options);
    }

    [Fact]
    public async Task GetEcnsAsync_ReturnsAllOrderedByCreatedAtDesc()
    {
        using var db = CreateInMemoryDbContext();
        db.Ecns.AddRange(
            new Ecn { EcnNumber = "ECN002", Status = "draft", CreatedAt = DateTime.UtcNow.AddDays(-1) },
            new Ecn { EcnNumber = "ECN001", Status = "draft", CreatedAt = DateTime.UtcNow });
        await db.SaveChangesAsync();

        var service = new EcnService(db);
        var result = await service.GetEcnsAsync();

        Assert.Equal(2, result.Count);
        Assert.Equal("ECN001", result[0].EcnNumber);
    }

    [Fact]
    public async Task GetEcnsAsync_FiltersByStatus()
    {
        using var db = CreateInMemoryDbContext();
        db.Ecns.AddRange(
            new Ecn { EcnNumber = "ECN001", Status = "draft" },
            new Ecn { EcnNumber = "ECN002", Status = "published" });
        await db.SaveChangesAsync();

        var service = new EcnService(db);
        var result = await service.GetEcnsAsync("published");

        Assert.Single(result);
        Assert.Equal("ECN002", result[0].EcnNumber);
    }

    [Fact]
    public async Task GetEcnAsync_ReturnsDto_WhenFound()
    {
        using var db = CreateInMemoryDbContext();
        var ecn = new Ecn { EcnNumber = "ECN001", Status = "draft", CreatedAt = DateTime.UtcNow };
        db.Ecns.Add(ecn);
        await db.SaveChangesAsync();
        db.EcnAffectedBoms.Add(new EcnAffectedBom { EcnId = ecn.Id, BomId = Guid.NewGuid(), ActionType = "update" });
        await db.SaveChangesAsync();

        var service = new EcnService(db);
        var dto = await service.GetEcnAsync(ecn.Id);

        Assert.NotNull(dto);
        Assert.Equal("ECN001", dto!.EcnNumber);
        Assert.Single(dto.AffectedBoms);
    }

    [Fact]
    public async Task GetEcnAsync_ReturnsNull_WhenNotFound()
    {
        using var db = CreateInMemoryDbContext();
        var service = new EcnService(db);
        Assert.Null(await service.GetEcnAsync(Guid.NewGuid()));
    }

    [Fact]
    public async Task CreateEcnAsync_ReturnsId_WhenValid()
    {
        using var db = CreateInMemoryDbContext();
        var service = new EcnService(db);
        var req = new CreateEcnRequest
        {
            EcnNumber = "ECN001",
            ChangeDescription = "Update BOM",
            AffectedBoms = new List<CreateEcnAffectedBomRequest>
            {
                new CreateEcnAffectedBomRequest { BomId = Guid.NewGuid(), ActionType = "update" }
            }
        };

        var id = await service.CreateEcnAsync(req);

        Assert.NotEqual(Guid.Empty, id);
        var created = await db.Ecns.FirstAsync(e => e.Id == id);
        Assert.Equal("ECN001", created.EcnNumber);
        Assert.Single(created.AffectedBoms);
    }

    [Fact]
    public async Task CreateEcnAsync_ReturnsId_WithAutoGeneratedNumber_WhenNumberEmpty()
    {
        using var db = CreateInMemoryDbContext();
        var service = new EcnService(db);
        var req = new CreateEcnRequest { ChangeDescription = "Auto number" };

        var id = await service.CreateEcnAsync(req);

        Assert.NotEqual(Guid.Empty, id);
        var created = await db.Ecns.FirstAsync(e => e.Id == id);
        Assert.StartsWith("ECN", created.EcnNumber);
    }

    [Fact]
    public void GetEcnImpact_ReturnsImpactDto()
    {
        using var db = CreateInMemoryDbContext();
        var service = new EcnService(db);

        var impact = service.GetEcnImpact(Guid.NewGuid());

        Assert.NotNull(impact);
        Assert.Equal(150000m, impact!.TotalLossAmount);
        Assert.Equal(3, impact.AffectedItemCount);
        Assert.Equal(2, impact.AffectedWorkOrders.Count);
    }
}
